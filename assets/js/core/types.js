/**
 * 象限判定：由两个维度的**均分**与切分点比较得出。
 *
 * 为什么用均分而不是标准分：切分点与常模均值回答的是两个不同问题。
 *   - 切分点：「在本站题目上算不算高」→ 量表中点 4.0（中文文献对 ECR 四型的定界惯例）
 *   - 常模均值：「相对已发表样本处在什么位置」→ 只用于百分位
 * 若改用 z > 0 判型，就会拿引用样本的均值（3.40）当本站题目的切分线，
 * 产出「百分位 77 却判为低回避」这类自相矛盾的结果。详见 core/norms.js 文件头。
 *
 * @param {number} a 依恋焦虑维度均分（1–7）
 * @param {number} v 依恋回避维度均分（1–7）
 * @param {{anxiety:number, avoidance:number}} [cut]
 */
export function classify(a, v, cut = NORMS.cut) {
  const hiA = a > cut.anxiety;
  const hiV = v > cut.avoidance;
  if (hiA && hiV) return 'fearful';
  if (hiA) return 'anxious';
  if (hiV) return 'avoidant';
  return 'secure';
}

export function getType(key) {
  return TYPES[key] || TYPES.secure;
}

